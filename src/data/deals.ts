// 额度雷达的数据源。
// 每条都对应一个官方定价页/文档；改数据只需要改这个文件，页面在构建期直接渲染。
//
// 分类：
//   promo  厂商活动 —— 邮箱 / OAuth / 免注册即可开通
//   relay  可注册中转 —— 第三方聚合、网关、社区算力
//   cn     国内厂商 —— 有免费额度但注册要手机号 / 实名，单独成类
//   观察区 = 没有免费额度、邀请制，或已经无法注册的
//
// verifiedAt 写最后一次人工核对日期，超过 30 天页面会标「待复验」

export type DealKind = "promo" | "relay" | "cn";
export type SignupKind = "email" | "oauth" | "none" | "phone" | "invite" | "closed";
/** 额度发放节奏 */
export type Cadence = "daily" | "weekly" | "monthly" | "once" | "ongoing";

export interface Deal {
  id: string;
  kind: DealKind;
  /** 厂商名 */
  name: string;
  /** 归属说明，例如「Google · 官方」 */
  org: string;
  /** 活动类型，同时也是筛选维度 */
  type: string;
  /** 卡片主标题，写清楚给的是什么 */
  title: string;
  desc: string;
  /** 详情弹窗里的补充说明 */
  detail?: string;
  /** 额度一句话，例如「每天 100 积分」 */
  quota?: string;
  cadence?: Cadence;
  /** 领取步骤 */
  steps?: string[];
  /** 领取 / 注册入口 */
  url: string;
  /** 信息来源 */
  source: string;
  signup: SignupKind;
  tags: string[];
  /** 使用前需要知道的风险，仅中转站常见 */
  risk?: string[];
  /** 截止日期；null 表示长期有效 */
  endsAt: string | null;
  /** 最后一次人工核对日期 */
  verifiedAt: string;
}

export interface WatchedSite {
  name: string;
  reason: string;
  tone: "red" | "amber";
  /** 最后一次确认日期 */
  when: string;
  note: string;
}

